def introduce(name, department):
    """
    Introduce a person with their name and department.

    Parameters:
    name (str): The name of the person.
    department (str): The department the person belongs to.

    Returns:
    str: A formatted introduction string.
    """
    return f"Hello, my name is {name} and I work in the {department} department."

print(introduce("Alice", "Engineering"))



